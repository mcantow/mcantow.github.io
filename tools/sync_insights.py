#!/usr/bin/env python3
"""Sync the essay carousel with customernode.com/insights.

The cards between the INSIGHTS:START and INSIGHTS:END markers in index.html
are generated from the live Insights hub: every piece, newest first, with its
title, teaser, format, date and cover. Covers are saved under img/insights/
(raster covers as 960px-wide WebP, SVG covers as-is) with a content-hash
cache buster.

Runs on a schedule in .github/workflows/insights-sync.yml and on demand
(the CustomerNode release script dispatches it when a release goes live).

    python3 tools/sync_insights.py            # fetch the live hub, rewrite
    python3 tools/sync_insights.py --hub FILE # use a saved hub page (tests)
    python3 tools/sync_insights.py --check    # exit 1 if a rewrite is due

Refuses to write when the hub yields fewer pieces than the page already
shows, so a broken or partial hub page can never wipe the carousel.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import io
import json
import re
import sys
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
IMG_DIR = ROOT / "img" / "insights"
SOURCES = IMG_DIR / "sources.json"  # slug -> sha256 of the hub cover each file was made from
ORIGIN = "https://customernode.com"
HUB = ORIGIN + "/insights/"
COVER_WIDTH = 960
START_RE = re.compile(r"^([ \t]*)<!--INSIGHTS:START[^>]*-->\n", re.M)
END_RE = re.compile(r"^[ \t]*<!--INSIGHTS:END-->", re.M)
START_LINE = "<!--INSIGHTS:START (generated by tools/sync_insights.py from customernode.com/insights; do not edit by hand)-->"
UA = "michaelcantow.com insights sync"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read()


def parse_hub(page: str) -> list[dict]:
    """Every piece on the hub: data attributes on each card + its JSON-LD entry."""
    ld = {}
    for m in re.finditer(r'<script type="application/ld\+json">(.*?)</script>', page, re.S):
        try:
            data = json.loads(m.group(1))
        except ValueError:
            continue
        for node in data.get("@graph", []):
            if node.get("@type") == "Blog":
                for post in node.get("blogPost", []):
                    slug = post.get("@id", "").split("#")[-1]
                    if slug:
                        ld[slug] = post
    pieces = []
    for m in re.finditer(r"<article\b([^>]*\bdata-insight-card\b[^>]*)>", page, re.S):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', m.group(1)))
        slug = attrs.get("id", "")
        post = ld.get(slug, {})
        piece = {
            "slug": slug,
            "url": ORIGIN + html.unescape(attrs.get("data-onsite", "")),
            "title": html.unescape(post.get("headline") or attrs.get("data-title", "")),
            "teaser": html.unescape(post.get("description", "")),
            "format": attrs.get("data-format", "Article"),
            "date": post.get("datePublished", ""),
            "cover": html.unescape(attrs.get("data-cover", "")),
            "position": attrs.get("data-cover-position", "center") or "center",
        }
        if not (slug and attrs.get("data-onsite") and piece["title"] and re.fullmatch(r"\d{4}-\d{2}-\d{2}", piece["date"])):
            raise SystemExit(f"hub piece {slug or '?'} is missing its link, title or date; refusing to write")
        pieces.append(piece)
    pieces.sort(key=lambda p: p["date"], reverse=True)
    return pieces


def tm(text: str) -> str:
    """Escape, and write CustomerNode as CustomerNode™ with the site's mark markup."""
    text = text.replace("CustomerNode™", "CustomerNode")
    esc = html.escape(text, quote=True)
    if "CustomerNode" not in esc:
        return esc
    esc = esc.replace("CustomerNode", '<span class="tmw">CustomerNode<span class="tm">™</span></span>')
    return f'<span class="tmr">{esc}</span>'


def short_date(iso: str) -> str:
    d = date.fromisoformat(iso)
    return f"{d.strftime('%b')} {d.day}, {d.year}"


def save_cover(piece: dict, get=fetch) -> str | None:
    """Download and store the cover; return its page path with cache buster."""
    src = piece["cover"]
    if not src:
        return None
    raw = get(src if src.startswith("http") else ORIGIN + src)
    IMG_DIR.mkdir(parents=True, exist_ok=True)
    is_svg = src.lower().split("?")[0].endswith(".svg")
    out = IMG_DIR / f"{piece['slug']}.{'svg' if is_svg else 'webp'}"
    # Only a changed SOURCE rewrites a cover: re-encoding an unchanged cover
    # would churn its bytes and its cache buster on every run.
    sources = json.loads(SOURCES.read_text()) if SOURCES.exists() else {}
    src_hash = hashlib.sha256(raw).hexdigest()
    if out.exists() and sources.get(piece["slug"]) in (None, src_hash):
        if sources.get(piece["slug"]) is None:
            sources[piece["slug"]] = src_hash  # adopt a cover made before this script
            SOURCES.write_text(json.dumps(sources, indent=1, sort_keys=True) + "\n")
        return f"img/insights/{out.name}?v={hashlib.sha256(out.read_bytes()).hexdigest()[:8]}"
    sources[piece["slug"]] = src_hash
    SOURCES.write_text(json.dumps(sources, indent=1, sort_keys=True) + "\n")
    if is_svg:
        data = raw
    else:
        from PIL import Image  # raster covers only

        im = Image.open(io.BytesIO(raw)).convert("RGB")
        if im.width > COVER_WIDTH:
            im = im.resize((COVER_WIDTH, round(im.height * COVER_WIDTH / im.width)), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "WEBP", quality=86, method=6)
        data = buf.getvalue()
    out.write_bytes(data)
    digest = hashlib.sha256(out.read_bytes()).hexdigest()[:8]
    return f"img/insights/{out.name}?v={digest}"


def card(piece: dict, cover: str | None) -> str:
    if cover:
        cover_html = (f'<span class="ins-cover"><img src="{cover}" alt="" loading="lazy" decoding="async" '
                      f'style="object-position:{html.escape(piece["position"])}"></span>')
    else:
        cover_html = '<span class="ins-cover ins-cover--none"></span>'
    return (
        f'        <li><a class="ins-card" href="{html.escape(piece["url"])}" target="_blank" rel="noopener">\n'
        f"          {cover_html}\n"
        f'          <span class="ins-meta">{html.escape(piece["format"])} · <time datetime="{piece["date"]}">{short_date(piece["date"])}</time></span>\n'
        f'          <span class="ins-title">{tm(piece["title"])}</span>\n'
        f'          <span class="ins-hook">{tm(piece["teaser"])}</span>\n'
        f"        </a></li>\n"
    )


def rewrite(page: str, cards: str, count: int) -> str:
    start, end = START_RE.search(page), END_RE.search(page)
    if not start or not end or end.start() < start.end():
        raise SystemExit("INSIGHTS markers not found in index.html; refusing to write")
    current = page[start.end():end.start()].count('class="ins-card"')
    if count < max(1, current):
        raise SystemExit(f"hub lists {count} pieces but the page shows {current}; refusing to shrink the carousel")
    return page[:start.start()] + start.group(1) + START_LINE + "\n" + cards + page[end.start():]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--hub", help="read the hub page from this file instead of the network")
    ap.add_argument("--check", action="store_true", help="exit 1 if index.html is out of date; write nothing")
    args = ap.parse_args(argv)
    page = Path(args.hub).read_text(encoding="utf-8") if args.hub else fetch(HUB).decode("utf-8")
    pieces = parse_hub(page)
    index = INDEX.read_text(encoding="utf-8")
    cards = "".join(card(p, save_cover(p) if not args.check else _existing_cover(index, p)) for p in pieces)
    new = rewrite(index, cards, len(pieces))
    if new == index:
        print(f"insights: up to date ({len(pieces)} pieces)")
        return 0
    if args.check:
        print("insights: index.html is out of date")
        return 1
    INDEX.write_text(new, encoding="utf-8")
    print(f"insights: wrote {len(pieces)} pieces")
    return 0


def _existing_cover(index: str, piece: dict) -> str | None:
    m = re.search(rf'src="(img/insights/{re.escape(piece["slug"])}\.(?:webp|svg)\?v=[0-9a-f]+)"', index)
    return m.group(1) if m else None


if __name__ == "__main__":
    sys.exit(main())
